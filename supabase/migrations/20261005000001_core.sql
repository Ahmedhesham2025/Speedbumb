-- ---------------------------------------------------------------- policies

create function public.is_fleet_member(fid bigint, roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from public.memberships m
    where m.user_id = (select auth.uid())
      and m.fleet_id = fid
      and (roles is null or m.role = any (roles))
  );
$$;

