  using (id = (select auth.uid()));
create policy devices_update_own on public.devices for update to authenticated
  using (id = (select auth.uid())) with check (id = (select auth.uid()));

-- observations, spot_contributors: no policies on purpose (only reachable through RPCs).

create policy spots_select_confirmed on public.spots for select to authenticated
