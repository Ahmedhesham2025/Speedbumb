-- ---------------------------------------------------------------- RPCs

-- Creates or refreshes the caller's device row. Returns the device id (= the auth user id).
create function public.register_device(app_version text, os_api int, consent_version int, share_enabled boolean)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  insert into public.devices as d (id, app_version, os_api, consent_version, share_enabled)
  values (uid, register_device.app_version, register_device.os_api,
          register_device.consent_version, coalesce(register_device.share_enabled, false))
  on conflict (id) do update
    set app_version = excluded.app_version,
        os_api = excluded.os_api,
        consent_version = excluded.consent_version,
        share_enabled = excluded.share_enabled;
  return uid;
end;
$$;

-- Accepts up to 500 hazard observations. Element format:
--   {"client_obs_id": uuid, "kind": "jolt|known_hit|pass_clear", "lat": n, "lon": n,
--    "heading": 0-359, "speed_kmh": n, "peak": n, "kind_score": n, "side_score": n, "observed_at": iso8601}
-- The whole batch is rejected (22023) if any element is invalid. Returns the client ids the server
-- now holds (new or already known), so the phone can clear them from its outbox.
create function public.submit_observations(batch jsonb)
returns uuid[]
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  n int;
  bad int;
  recent int;
begin
  if uid is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  if not exists (select 1 from public.devices d where d.id = uid and d.share_enabled) then
    raise exception 'device not registered or sharing is off' using errcode = '42501';
  end if;
  if batch is null or jsonb_typeof(batch) <> 'array' then
    raise exception 'batch must be a JSON array' using errcode = '22023';
  end if;
  n := jsonb_array_length(batch);
  if n = 0 then
    return '{}'::uuid[];
  end if;
  if n > 500 then
    raise exception 'batch too large (% > 500)', n using errcode = '22023';
  end if;

  -- Egypt / MENA box only; times within the last 30 days.
  select count(*) into bad
  from jsonb_array_elements(batch) e
  where not coalesce(
    jsonb_typeof(e) = 'object'
    and e ->> 'client_obs_id' is not null
    and e ->> 'kind' in ('jolt', 'known_hit', 'pass_clear')
    and jsonb_typeof(e -> 'lat') = 'number'
    and jsonb_typeof(e -> 'lon') = 'number'
    and (e ->> 'lat')::double precision between 12 and 38
    and (e ->> 'lon')::double precision between 24 and 60
    and (e ->> 'observed_at')::timestamptz between now() - interval '30 days' and now() + interval '1 hour',
    false);
  if bad > 0 then
    raise exception '% invalid observation(s) in batch', bad using errcode = '22023';
  end if;

  select count(*) into recent
  from public.observations o
  where o.device_id = uid and o.created_at > now() - interval '1 day';
  if recent + n > 2000 then
    raise exception 'daily upload limit reached' using errcode = '54000';
  end if;

  insert into public.observations
    (device_id, client_obs_id, kind, geom, heading, speed_kmh, peak, kind_score, side_score, observed_hour)
  select uid,
         (e ->> 'client_obs_id')::uuid,
         e ->> 'kind',
         extensions.st_setsrid(
           extensions.st_makepoint((e ->> 'lon')::double precision, (e ->> 'lat')::double precision), 4326
         )::extensions.geography,
         (e ->> 'heading')::smallint,
         (e ->> 'speed_kmh')::smallint,
         (e ->> 'peak')::real,
         (e ->> 'kind_score')::real,
         (e ->> 'side_score')::real,
         date_trunc('hour', (e ->> 'observed_at')::timestamptz)
  from jsonb_array_elements(batch) e
  on conflict (device_id, client_obs_id) do nothing;

  return (select array_agg(distinct (e ->> 'client_obs_id')::uuid) from jsonb_array_elements(batch) e);
end;
$$;

-- Confirmed spots around a point; radius capped at 10 km.
create function public.spots_near(lat double precision, lon double precision, radius_m int default 3000)
returns table (
  id bigint,
  latitude double precision,
  longitude double precision,
  heading smallint,
  kind text,
  side text,
  severity real,
  n_devices int,
  last_hit timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select s.id,
         extensions.st_y(s.geom::extensions.geometry),
         extensions.st_x(s.geom::extensions.geometry),
         s.heading, s.kind, s.side, s.severity, s.n_devices, s.last_hit
  from public.spots s
  where s.status = 'confirmed'
    and extensions.st_dwithin(
          s.geom,
          extensions.st_setsrid(extensions.st_makepoint(spots_near.lon, spots_near.lat), 4326)::extensions.geography,
          least(greatest(coalesce(spots_near.radius_m, 3000), 0), 10000)::double precision)
  order by s.id
  limit 5000;
$$;

-- Deletes the caller's device and, by cascade, its observations, contributions, trips and crash reports.
-- Merged spots stay: they no longer point to any device.
create function public.forget_me()
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() is null then
    raise exception 'not signed in' using errcode = '42501';
  end if;
  delete from public.devices d where d.id = auth.uid();
end;
$$;

-- ---------------------------------------------------------------- aggregation (server only)

-- Merges unprocessed observations into spots (15 m, heading within 45 degrees), updates counters and
-- status, and deletes processed observations older than 30 days. Returns how many it processed.
create function public.aggregate_observations()
returns int
language plpgsql
security definer
set search_path = ''
as $$
declare
  o record;
  sid bigint;
  is_hit boolean;
  touched bigint[] := '{}';
  done int := 0;
begin
  for o in
    select ob.id, ob.device_id, ob.kind, ob.geom, ob.heading, ob.peak, ob.kind_score, ob.side_score, ob.observed_hour
    from public.observations ob
    where not ob.processed
    order by ob.id
    for update skip locked
  loop
    is_hit := o.kind <> 'pass_clear';
    select s.id into sid
    from public.spots s
    where s.status <> 'retired'
      and extensions.st_dwithin(s.geom, o.geom, 15)
      and (s.heading is null or o.heading is null
           or abs(((s.heading::int - o.heading::int) % 360 + 540) % 360 - 180) <= 45)
    order by extensions.st_distance(s.geom, o.geom)
    limit 1;

    if sid is null and is_hit then
      insert into public.spots (geom, heading, kind, side, severity, first_seen, last_hit)
      values (o.geom, o.heading,
              case when o.kind_score is null then null when o.kind_score >= 0.5 then 'pothole' else 'bump' end,
              case when o.side_score is null then null when o.side_score > 0.33 then 'right'
                   when o.side_score < -0.33 then 'left' else 'both' end,
              o.peak, o.observed_hour, o.observed_hour)
      returning id into sid;
    end if;

    if sid is not null then
      insert into public.spot_contributors as c (spot_id, device_id, hits, clears, last_at)
      values (sid, o.device_id, case when is_hit then 1 else 0 end, case when is_hit then 0 else 1 end, o.observed_hour)
      on conflict (spot_id, device_id) do update
        set hits = c.hits + excluded.hits,
            clears = c.clears + excluded.clears,
            last_at = greatest(c.last_at, excluded.last_at);
      if is_hit then
        update public.spots s
        set last_hit = greatest(s.last_hit, o.observed_hour),
            severity = case when o.peak is null then s.severity
                            else coalesce(0.8 * s.severity + 0.2 * o.peak, o.peak) end
        where s.id = sid;
      end if;
      touched := touched || sid;
    end if;

    update public.observations set processed = true where id = o.id;
    done := done + 1;
  end loop;

  update public.spots s
  set n_devices = c.n_dev, n_hits = c.n_hits, n_clear = c.n_clear, updated_at = now()
  from (
    select sc.spot_id,
           count(*) filter (where sc.hits > 0)::int as n_dev,
           sum(sc.hits)::int as n_hits,
           sum(sc.clears)::int as n_clear
    from public.spot_contributors sc
    where sc.spot_id = any (touched)
    group by sc.spot_id
  ) c
  where s.id = c.spot_id;

  -- Confirm with 3 devices (2 if one is a fleet driver's phone) and at least half of the passes hit.
  update public.spots s
  set status = case
      when s.n_hits::real / greatest(s.n_hits + s.n_clear, 1) >= 0.5
           and s.n_devices >= case when exists (
                 select 1 from public.spot_contributors sc
                 join public.drivers d on d.device_id = sc.device_id and d.active
                 where sc.spot_id = s.id and sc.hits > 0) then 2 else 3 end
        then 'confirmed'
      when s.status = 'confirmed' then 'stale'
      else s.status end
  where s.id = any (touched) and s.status <> 'retired';

  delete from public.observations ob where ob.processed and ob.created_at < now() - interval '30 days';
  return done;
end;
$$;

