-- Bump Beeper core schema: shared bump map + fleet pilot.
-- Rules: RLS on for every table, deny by default; clients write only through SECURITY DEFINER RPCs
-- with an empty search_path; raw observations are merged into spots and deleted after 30 days.

create extension if not exists postgis with schema extensions;

-- ---------------------------------------------------------------- tables

create table public.devices (
  id uuid primary key default auth.uid() references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  app_version text,
  os_api int,
  consent_version int,
  share_enabled boolean not null default false,
  trust real not null default 1.0
);

-- One row per hazard event a phone reports. No tracks: single points, time rounded to the hour.
create table public.observations (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.devices (id) on delete cascade,
  client_obs_id uuid not null,
  kind text not null check (kind in ('jolt', 'known_hit', 'pass_clear')),
  geom extensions.geography(Point, 4326) not null,
  heading smallint check (heading between 0 and 359),
  speed_kmh smallint check (speed_kmh between 0 and 250),
  peak real,
  kind_score real,
  side_score real,
  observed_hour timestamptz not null,
  processed boolean not null default false,
  created_at timestamptz not null default now(),
  unique (device_id, client_obs_id)
);
create index observations_unprocessed_idx on public.observations (id) where not processed;
create index observations_device_day_idx on public.observations (device_id, created_at);

create table public.spots (
  id bigint generated by default as identity primary key,
  geom extensions.geography(Point, 4326) not null,
  heading smallint check (heading between 0 and 359),
  kind text,
  side text,
  severity real,
  n_devices int not null default 0,
  n_hits int not null default 0,
  n_clear int not null default 0,
  status text not null default 'candidate' check (status in ('candidate', 'confirmed', 'stale', 'retired')),
  first_seen timestamptz not null default now(),
  last_hit timestamptz,
  updated_at timestamptz not null default now()
);
create index spots_geom_idx on public.spots using gist (geom);

create table public.spot_contributors (
  spot_id bigint not null references public.spots (id) on delete cascade,
  device_id uuid not null references public.devices (id) on delete cascade,
  hits int not null default 0,
  clears int not null default 0,
  last_at timestamptz,
  primary key (spot_id, device_id)
);
create index spot_contributors_device_idx on public.spot_contributors (device_id);

create table public.fleets (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at timestamptz not null default now()
);

create table public.memberships (
  user_id uuid not null references auth.users (id) on delete cascade,
  fleet_id bigint not null references public.fleets (id) on delete cascade,
  role text not null check (role in ('owner', 'admin', 'viewer')),
  primary key (user_id, fleet_id)
);
create index memberships_fleet_idx on public.memberships (fleet_id);

create table public.vehicles (
  id bigint generated by default as identity primary key,
  fleet_id bigint not null references public.fleets (id) on delete cascade,
  label text not null
);
create index vehicles_fleet_idx on public.vehicles (fleet_id);

create table public.drivers (
  id bigint generated by default as identity primary key,
  fleet_id bigint not null references public.fleets (id) on delete cascade,
  display_name text not null,
  device_id uuid references public.devices (id) on delete set null,
  vehicle_id bigint references public.vehicles (id) on delete set null,
  on_shift boolean not null default false,
  active boolean not null default true
);
create index drivers_fleet_idx on public.drivers (fleet_id);
create index drivers_device_idx on public.drivers (device_id);
create index drivers_vehicle_idx on public.drivers (vehicle_id);

create table public.invites (
  code text primary key,
  fleet_id bigint not null references public.fleets (id) on delete cascade,
  driver_id bigint references public.drivers (id) on delete cascade,
  expires_at timestamptz not null default now() + interval '7 days',
  used_at timestamptz
);
create index invites_fleet_idx on public.invites (fleet_id);
create index invites_driver_idx on public.invites (driver_id);

create table public.trips (
  id bigint generated by default as identity primary key,
  device_id uuid not null references public.devices (id) on delete cascade,
  driver_id bigint references public.drivers (id) on delete set null,
  fleet_id bigint references public.fleets (id) on delete cascade,
  started_at timestamptz not null,
  ended_at timestamptz,
  distance_m int,
  score smallint check (score between 0 and 100),
  moving_s int,
  speeding_s int,
  harsh_brakes int,
  harsh_accels int,
  harsh_corners int,
  swerves int,
  bumps_fast int,
  phone_use int
);
create index trips_device_idx on public.trips (device_id);
create index trips_fleet_idx on public.trips (fleet_id);
create index trips_driver_idx on public.trips (driver_id);

create table public.trip_events (
  id bigint generated by default as identity primary key,
  trip_id bigint not null references public.trips (id) on delete cascade,
  kind text not null,
  geom extensions.geography(Point, 4326),
  speed_kmh smallint,
  value real,
  at timestamptz not null
);
create index trip_events_trip_idx on public.trip_events (trip_id);

create table public.crash_reports (
  id bigint generated by default as identity primary key,
  device_id uuid not null default auth.uid() references public.devices (id) on delete cascade,
  app_version text,
  at timestamptz not null default now(),
  stack text check (length(stack) <= 20000),
  model text
);
create index crash_reports_device_idx on public.crash_reports (device_id);

