revoke execute on function public.prune_training_data() from public, anon, authenticated;
revoke execute on function public.training_i16(bytea, real) from public, anon, authenticated;
revoke execute on function public.training_export(date) from public, anon, authenticated;
grant execute on function public.set_training_consent(boolean, int) to authenticated;
grant execute on function public.submit_training_samples(jsonb) to authenticated;
grant execute on function public.training_export(date) to service_role;

-- Prune daily where pg_cron exists (same pattern as the other jobs).
do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron with schema pg_catalog;
    perform cron.schedule('prune-training-data', '41 3 * * *', 'select public.prune_training_data()');
  end if;
exception when others then
  raise notice 'pg_cron not scheduled: %', sqlerrm;
end;
$$;
